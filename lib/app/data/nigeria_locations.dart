  /// Search states by name
  static List<NigeriaLocation> searchStates(String query) {
    if (query.isEmpty) return states;
    final q = query.toLowerCase();
    return states.where((s) => s.state.toLowerCase().contains(q)).toList();
  }

  /// Search LGAs within a state
  static List<NigeriaLGA> searchLGAs(NigeriaLocation state, String query) {
    if (query.isEmpty) return state.lgas;
    final q = query.toLowerCase();
    return state.lgas.where((l) => l.name.toLowerCase().contains(q)).toList();
  }

  /// Get state by name
  static NigeriaLocation? getState(String name) {
    try {
      return states.firstWhere((s) => s.state == name);
    } catch (_) {
      return null;
    }
  }

  /// Get LGA by name within a state
  static NigeriaLGA? getLGA(String stateName, String lgaName) {
    final state = getState(stateName);
    if (state == null) return null;
    try {
      return state.lgas.firstWhere((l) => l.name == lgaName);
    } catch (_) {
      return null;
    }
  }
